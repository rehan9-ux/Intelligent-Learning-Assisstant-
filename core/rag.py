import json
import requests
from typing import List, Dict, Any, Optional, Tuple, Generator
from pathlib import Path

from core.config import (
    OLLAMA_BASE_URL,
    OLLAMA_LLM_MODEL,
    TOP_K_RESULTS,
    MAX_DISTANCE_THRESHOLD
)
from core.ingest import query_vector_store
from core.prompts import (
    build_adaptive_system_prompt,
    build_rag_user_prompt,
    DEFAULT_SYSTEM_PROMPT
)


def format_retrieved_context(chunks: List[Dict[str, Any]]) -> Tuple[str, List[Dict[str, Any]]]:
    """
    Formats top-k retrieved chunks into clean numbered context passages and extracts citation metadata.
    """
    if not chunks:
        return "No relevant study material found in the uploaded documents.", []

    formatted_passages = []
    sources = []
    seen_sources = set()

    for idx, chunk in enumerate(chunks):
        meta = chunk.get("metadata", {})
        source_file = meta.get("source_file", "Unknown Document")
        page_num = meta.get("page_number", "N/A")
        sim_score = chunk.get("similarity_score", 0.0)
        text = chunk.get("text", "").strip()

        # Add to formatted context block for LLM
        passage_header = f"[Passage {idx + 1} | Source: {source_file} (Page {page_num}) | Relevance: {sim_score * 100:.1f}%]"
        formatted_passages.append(f"{passage_header}\n{text}")

        # Add to unique sources list for UI citations
        source_key = (source_file, page_num)
        if source_key not in seen_sources:
            seen_sources.add(source_key)
            sources.append({
                "source_file": source_file,
                "page_number": page_num,
                "similarity_score": sim_score,
                "snippet": text[:180] + "..." if len(text) > 180 else text
            })

    context_str = "\n\n".join(formatted_passages)
    return context_str, sources


def query_rag_stream(
    question: str,
    student_profile: Optional[Dict[str, Any]] = None,
    top_k: int = TOP_K_RESULTS,
    temperature: float = 0.3,
    max_tokens: int = 700
) -> Generator[str, None, None]:
    """
    Executes RAG pipeline and yields tokens in real-time as generated by Ollama.
    Ideal for Streamlit's st.write_stream().
    """
    clean_q = question.strip()
    if not clean_q:
        yield "Please enter a valid question."
        return

    # 1. Semantic Retrieval
    chunks = query_vector_store(clean_q, top_k=top_k)

    # Check if retrieval returned usable content
    best_dist = chunks[0]["distance"] if chunks else 999.0
    if not chunks or best_dist > MAX_DISTANCE_THRESHOLD:
        yield "I checked your uploaded study materials, but couldn't find relevant content regarding this question. Please upload notes covering this topic or try rephrasing."
        return

    context_str, _ = format_retrieved_context(chunks)

    # 2. Build Adaptive Prompts
    if student_profile:
        system_prompt = build_adaptive_system_prompt(
            level=student_profile.get("level", "beginner"),
            weak_topics=student_profile.get("weak_topics", []),
            explanation_style=student_profile.get("explanation_style", "analogies")
        )
    else:
        system_prompt = DEFAULT_SYSTEM_PROMPT

    user_prompt = build_rag_user_prompt(context_passages=context_str, question=clean_q)

    # 3. Stream from Ollama API
    url = f"{OLLAMA_BASE_URL}/api/generate"
    payload = {
        "model": OLLAMA_LLM_MODEL,
        "prompt": user_prompt,
        "system": system_prompt,
        "stream": True,
        "options": {
            "temperature": temperature,
            "num_predict": max_tokens
        }
    }

    try:
        resp = requests.post(url, json=payload, stream=True, timeout=120)
        if resp.status_code != 200:
            yield f"Error connecting to local LLM ({resp.status_code}): {resp.text}"
            return

        for line in resp.iter_lines():
            if line:
                chunk_data = json.loads(line.decode("utf-8"))
                token = chunk_data.get("response", "")
                if token:
                    yield token
                if chunk_data.get("done", False):
                    break
    except Exception as e:
        yield f"Error during response generation: {str(e)}"


def query_rag(
    question: str,
    student_profile: Optional[Dict[str, Any]] = None,
    top_k: int = TOP_K_RESULTS,
    temperature: float = 0.3
) -> Dict[str, Any]:
    """
    Synchronous helper returning full generated answer, sources, and context.
    Used for programmatic testing and FastAPI endpoints.
    """
    clean_q = question.strip()
    if not clean_q:
        return {
            "answer": "Please enter a valid question.",
            "sources": [],
            "context_passages": "",
            "is_grounded": False
        }

    # 1. Semantic Retrieval
    chunks = query_vector_store(clean_q, top_k=top_k)
    best_dist = chunks[0]["distance"] if chunks else 999.0

    if not chunks or best_dist > MAX_DISTANCE_THRESHOLD:
        return {
            "answer": "I checked your uploaded study materials, but couldn't find relevant content regarding this question. Please upload notes covering this topic.",
            "sources": [],
            "context_passages": "",
            "is_grounded": False
        }

    context_str, sources = format_retrieved_context(chunks)

    # 2. Build Prompts
    if student_profile:
        system_prompt = build_adaptive_system_prompt(
            level=student_profile.get("level", "beginner"),
            weak_topics=student_profile.get("weak_topics", []),
            explanation_style=student_profile.get("explanation_style", "analogies")
        )
    else:
        system_prompt = DEFAULT_SYSTEM_PROMPT

    user_prompt = build_rag_user_prompt(context_passages=context_str, question=clean_q)

    # 3. Call Ollama
    url = f"{OLLAMA_BASE_URL}/api/generate"
    payload = {
        "model": OLLAMA_LLM_MODEL,
        "prompt": user_prompt,
        "system": system_prompt,
        "stream": False,
        "options": {
            "temperature": temperature,
            "num_predict": 500
        }
    }

    try:
        resp = requests.post(url, json=payload, timeout=120)
        if resp.status_code == 200:
            answer = resp.json().get("response", "").strip()
            return {
                "answer": answer,
                "sources": sources,
                "context_passages": context_str,
                "is_grounded": True,
                "model": OLLAMA_LLM_MODEL
            }
        else:
            return {
                "answer": f"Ollama generation error ({resp.status_code}): {resp.text}",
                "sources": sources,
                "context_passages": context_str,
                "is_grounded": False
            }
    except Exception as e:
        return {
            "answer": f"Generation error: {str(e)}",
            "sources": sources,
            "context_passages": context_str,
            "is_grounded": False
        }
